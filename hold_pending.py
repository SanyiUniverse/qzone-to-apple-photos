"""Copy withheld originals to an explicit folder; no Photos or network access."""
import argparse
from collections import Counter
import datetime as dt
import hashlib
import json
import os
from pathlib import Path
import shutil
import tempfile

TOOL = 'qzone-to-apple-photos/hold_pending'
README_MARKER = '<!-- Generated by ' + TOOL + ' -->'


def sha(path):
    with Path(path).open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def verify_or_copy(source, target, expected):
    if not source.is_file() or sha(source) != expected:
        raise RuntimeError('Original checksum mismatch: ' + str(source))
    if target.exists():
        if not target.is_file() or sha(target) != expected:
            raise RuntimeError('Conflicting destination; not overwritten: ' + str(target))
        return False
    target.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.hold-', dir=target.parent)
    os.close(fd)
    temporary = Path(name)
    try:
        shutil.copy2(source, temporary)
        if sha(temporary) != expected:
            raise RuntimeError('Backup checksum mismatch: ' + str(source))
        # Publish without ever replacing an existing file, including a race.
        os.link(temporary, target)
        if sha(target) != expected:
            raise RuntimeError('Published backup checksum mismatch: ' + str(target))
    finally:
        temporary.unlink(missing_ok=True)
    return True


def check_generated(path, markdown=False):
    if not path.exists():
        return
    try:
        text = path.read_text()
        valid = text.startswith(README_MARKER) if markdown else json.loads(text).get('tool') == TOOL
    except (ValueError, OSError, AttributeError):
        valid = False
    if not valid:
        raise RuntimeError('Unrecognized report; not overwritten: ' + str(path))


def atomic_text(path, content):
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix='.hold-report-', dir=path.parent)
    temporary = Path(name)
    try:
        with os.fdopen(fd, 'w') as stream:
            stream.write(content)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def backup(manifest, destination, result_path=None):
    manifest, destination = Path(manifest).resolve(), Path(destination).resolve()
    rows = json.loads(manifest.read_text())
    if not isinstance(rows, list):
        raise ValueError('Expected a prepared-items JSON list')
    pending = [x for x in rows if x.get('status') != 'capture_ready']
    report_path, readme_path = destination / '暂缓项目清单.json', destination / '说明.md'
    report_paths = list(dict.fromkeys([report_path] + ([Path(result_path).resolve()] if result_path else [])))
    for path in report_paths:
        check_generated(path)
    check_generated(readme_path, markdown=True)
    sources, targets = set(), set()
    jobs = []
    for item in pending:
        source = Path(item['original_path']).resolve()
        # Keep the original album directory and the downloaded original filename.
        relative = Path('原始文件') / source.parent.name / source.name
        target = destination / relative
        if not target.resolve().is_relative_to(destination):
            raise ValueError('Backup target escapes destination: ' + str(target))
        if source == target.resolve() or source in report_paths or source == readme_path:
            raise ValueError('Backup/report destination overlaps an original')
        if target in targets:
            raise ValueError('Duplicate backup destination: ' + str(target))
        targets.add(target)
        sources.add(source)
        jobs.append((item, source, target, relative))
    if (sources | targets) & set(report_paths + [readme_path]) or sources & targets:
        raise ValueError('Report or backup destination overlaps a media file')
    copied, items = 0, []
    for item, source, target, relative in jobs:
        expected = item['original_sha256']
        copied += verify_or_copy(source, target, expected)
        # Allowlist evidence: never copy raw API responses, URLs, or credentials.
        evidence = {key: item.get(key) for key in (
            'status', 'file_type', 'precision', 'target_source', 'capture_wall_time',
            'date_only', 'timezone_status', 'flags', 'conflicts')}
        evidence['qq_dates'] = {key: item.get('qq_source_values', {}).get(key)
            for key in ('originalTime', 'rawshoottime', 'shoottime', 'uploadtime')}
        items.append({'album': item.get('album'), 'album_id': item.get('album_id'),
            'pic_key': item.get('pic_key'), 'original_path': str(source),
            'backup_path': str(target), 'relative_path': str(relative),
            'sha256': expected, 'bytes': target.stat().st_size, 'verified': True,
            'evidence': evidence})
    result = {'tool': TOOL, 'schema_version': 1, 'created_at': dt.datetime.now().astimezone().isoformat(),
        'source_manifest': str(manifest), 'destination': str(destination),
        'prepared_count': len(rows), 'pending_count': len(items), 'copied_count': copied,
        'reused_count': len(items) - copied, 'all_sha256_verified': True,
        'originals_modified': False, 'photos_operations': False, 'items': items}
    status = Counter(x['evidence']['status'] for x in items)
    reasons = {'unknown': '缺少可证明的完整拍摄时间', 'date_only': '只有日期，缺少时分秒',
               'needs_review': '日期冲突、格式不支持或其他证据需要确认'}
    lines = [README_MARKER, '# QQ 相册暂缓迁移的原始文件', '',
        f'本次核验 {len(items)} 项。所有副本的 SHA-256 均与原始下载记录一致；未改动媒体内容或元数据。', '',
        '这些项目暂不导入 Apple 照片，也不属于可从 QQ 删除的已验证项目。',
        '原始备份继续保留。这里按原始相册文件夹和下载文件名保存副本；相册中文名称及逐项证据见“暂缓项目清单.json”。', '',
        '暂缓原因：', '']
    lines += [f'- {reasons.get(key, key)}：{count} 项。' for key, count in sorted(status.items())]
    lines += ['', 'QQ 上传时间不作为缺失拍摄时间的替代。只有年月日的项目不补造时分秒。',
        '重复运行会重新校验已有副本，不覆盖内容不同的同名文件；旧备份不会自动删除。',
        '若以后有证据确定日期，应先更新迁移计划并完成测试，再决定是否导入。', '']
    encoded = json.dumps(result, ensure_ascii=False, indent=2) + '\n'
    for path in report_paths:
        atomic_text(path, encoded)
    atomic_text(readme_path, '\n'.join(lines))
    return {k: v for k, v in result.items() if k != 'items'}


def main():
    os.umask(0o077)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--manifest', type=Path, required=True, help='Prepared-items JSON list')
    parser.add_argument('--destination', type=Path, required=True, help='Explicit backup directory')
    parser.add_argument('--result', type=Path, help='Optional additional verification JSON path')
    args = parser.parse_args()
    print(json.dumps(backup(args.manifest, args.destination, args.result), ensure_ascii=False))


if __name__ == '__main__':
    main()
